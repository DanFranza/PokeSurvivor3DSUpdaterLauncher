#!/usr/bin/env python3
"""Validate the five-language catalog and generate its C++ table."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('fr', 'en', 'es', 'it', 'pt')


def catalog():
    rows = []
    seen = set()
    for number, line in enumerate((ROOT / 'translations/launcher.tsv').read_text().splitlines(), 1):
        cells = [value.replace('\\n', '\n') for value in line.split('\t')]
        if len(cells) != 5 or any(not value for value in cells):
            raise ValueError(f'Line {number}: five nonempty translations required')
        if cells[0] in seen:
            raise ValueError(f'Line {number}: duplicate French key')
        seen.add(cells[0])
        placeholders = re.findall(r'\{\d+\}|%[-+0-9.]*l?[fsdXu]', cells[0])
        for language, value in zip(LANGUAGES, cells):
            if sorted(re.findall(r'\{\d+\}|%[-+0-9.]*l?[fsdXu]', value)) != sorted(placeholders):
                raise ValueError(f'Line {number}: placeholders differ in {language}')
        rows.append(cells)
    return rows


def generated():
    rows = catalog()
    return '// Generated by tools/generate_translations.py; edit translations/launcher.tsv.\n' + ''.join(
        '    {' + ', '.join(json.dumps(cell, ensure_ascii=False) for cell in row) + '},\n'
        for row in rows)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'source/translations.inc'
    text = generated()
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.error('Generated translations are out of date; run this script without --check')
    else:
        target.write_text(text)
    print(f'{len(catalog())} messages validated in five languages.')
